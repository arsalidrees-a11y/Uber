#!/usr/bin/env node
/* Concatenates src/behaviors/*.js into public/uber-learn.js in filename order.
   00-core.js runs first and defines window.UberLearn; every later file is its
   own IIFE that delegates from document and may use window.UberLearn.
   One file per component means parallel authors never touch the same file.
   Run: npm run behaviors */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const dir = 'src/behaviors';
const files = readdirSync(dir).filter((f) => f.endsWith('.js')).sort();
if (!files[0].startsWith('00-core')) { console.error('00-core.js must sort first'); process.exit(1); }

const out = ['/* GENERATED by scripts/build-behaviors.mjs - do not edit.',
             ' * Sources: ' + files.join(', '), ' */', ''];
for (const f of files) {
  out.push(`/* ===== ${f} ===== */`, readFileSync(`${dir}/${f}`, 'utf8').trimEnd(), '');
}
const js = out.join('\n');
writeFileSync('public/uber-learn.js', js);
console.log(`uber-learn.js  ${files.length} files  ${(js.length / 1024).toFixed(1)} kB`);
